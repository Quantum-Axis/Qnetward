-- Uptime monitors: targets the server checks on a schedule, and the outcome
-- of each check. Both belong to a workspace and sit behind the same row-level
-- security policy as alert rules (ADR 0009).
CREATE TABLE IF NOT EXISTS monitors (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
	name TEXT NOT NULL,
	protocol TEXT NOT NULL CHECK (protocol IN ('ping', 'tcpping')),
	target TEXT NOT NULL,
	port INTEGER,
	interval_seconds INTEGER NOT NULL CHECK (interval_seconds >= 60),
	notify_email TEXT NOT NULL DEFAULT '',
	enabled BOOLEAN NOT NULL DEFAULT TRUE,
	status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'up', 'down')),
	last_checked_at TIMESTAMPTZ,
	last_status_change_at TIMESTAMPTZ,
	last_rtt_ms DOUBLE PRECISION,
	last_error TEXT NOT NULL DEFAULT '',
	next_run_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_monitors_workspace_target
	ON monitors (workspace_id, protocol, target, COALESCE(port, 0));
CREATE INDEX IF NOT EXISTS idx_monitors_due ON monitors (next_run_at) WHERE enabled;

CREATE TABLE IF NOT EXISTS monitor_checks (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	monitor_id BIGINT NOT NULL REFERENCES monitors(id) ON DELETE CASCADE,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	checked_at TIMESTAMPTZ NOT NULL,
	ok BOOLEAN NOT NULL,
	rtt_ms DOUBLE PRECISION,
	loss_percent DOUBLE PRECISION NOT NULL DEFAULT 0,
	error TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_monitor_checks_monitor ON monitor_checks (monitor_id, checked_at DESC);
CREATE INDEX IF NOT EXISTS idx_monitor_checks_checked_at ON monitor_checks (checked_at);

GRANT SELECT, INSERT, UPDATE, DELETE ON monitors, monitor_checks TO qnetward_tenant;

ALTER TABLE monitors ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS workspace_isolation ON monitors;
CREATE POLICY workspace_isolation ON monitors
	TO qnetward_tenant
	USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint)
	WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint);

ALTER TABLE monitor_checks ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS workspace_isolation ON monitor_checks;
CREATE POLICY workspace_isolation ON monitor_checks
	TO qnetward_tenant
	USING (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint)
	WITH CHECK (workspace_id = NULLIF(current_setting('app.workspace_id', true), '')::bigint);
