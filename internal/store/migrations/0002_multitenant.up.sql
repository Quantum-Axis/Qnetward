-- Introduces tenants (organizations/workspaces). Every user belongs to
-- exactly one tenant, auto-created at signup for now; a members join
-- table for inviting teammates into an existing tenant is a follow-up.
--
-- Row-Level Security is enabled and FORCED on alert_rules: the app sets
-- current_setting('app.tenant_id') per request (see store.withTenant),
-- and even the owning/table-creating role is subject to the policy
-- (FORCE), so the database itself refuses a cross-tenant row, not just
-- the WHERE clause in Go. This requires the connecting role NOT be a
-- Postgres superuser — superusers always bypass RLS regardless of FORCE.
--
-- results is NOT RLS-enforced yet: its rows are written by a single
-- background worker that batches ResultRecords from many requests
-- (possibly many tenants) into one multi-row INSERT per flush, which is
-- incompatible with a single per-transaction "current tenant" session
-- variable. It still gets a tenant_id column (for future per-tenant
-- history views) and stays isolated by the existing user_id filter,
-- which every read already requires.

CREATE TABLE IF NOT EXISTS tenants (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE users
	ADD COLUMN IF NOT EXISTS tenant_id BIGINT REFERENCES tenants(id);

-- Backfill: one tenant per existing user, named after them, for any
-- database that already has users from before tenants existed.
INSERT INTO tenants (name)
SELECT COALESCE(NULLIF(TRIM(u.name), ''), u.email) || '''s workspace'
FROM users u
WHERE u.tenant_id IS NULL;

WITH assigned AS (
	SELECT u.id AS user_id, t.id AS tenant_id,
		ROW_NUMBER() OVER (PARTITION BY u.id ORDER BY t.id DESC) AS rn
	FROM users u
	JOIN tenants t
		ON t.name = COALESCE(NULLIF(TRIM(u.name), ''), u.email) || '''s workspace'
	WHERE u.tenant_id IS NULL
)
UPDATE users
SET tenant_id = assigned.tenant_id
FROM assigned
WHERE users.id = assigned.user_id
	AND assigned.rn = 1;

ALTER TABLE users
	ALTER COLUMN tenant_id SET NOT NULL;

CREATE INDEX IF NOT EXISTS idx_users_tenant_id
	ON users (tenant_id);

ALTER TABLE alert_rules
	ADD COLUMN IF NOT EXISTS tenant_id BIGINT REFERENCES tenants(id);

UPDATE alert_rules ar
SET tenant_id = u.tenant_id
FROM users u
WHERE ar.user_id = u.id
	AND ar.tenant_id IS NULL;

ALTER TABLE alert_rules
	ALTER COLUMN tenant_id SET NOT NULL;

CREATE INDEX IF NOT EXISTS idx_alert_rules_tenant_id
	ON alert_rules (tenant_id);

ALTER TABLE alert_rules ENABLE ROW LEVEL SECURITY;
ALTER TABLE alert_rules FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS tenant_isolation ON alert_rules;
CREATE POLICY tenant_isolation ON alert_rules
	USING (tenant_id = current_setting('app.tenant_id', true)::bigint)
	WITH CHECK (tenant_id = current_setting('app.tenant_id', true)::bigint);

ALTER TABLE results
	ADD COLUMN IF NOT EXISTS tenant_id BIGINT REFERENCES tenants(id);

UPDATE results r
SET tenant_id = u.tenant_id
FROM users u
WHERE r.user_id = u.id
	AND r.tenant_id IS NULL;

ALTER TABLE results
	ALTER COLUMN tenant_id SET NOT NULL;

CREATE INDEX IF NOT EXISTS idx_results_tenant_id
	ON results (tenant_id);
