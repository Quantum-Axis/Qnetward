-- Baseline schema, matching what setupSchema() previously created inline
-- in store.go for a default-named results table (table name "results").
--
-- A custom result table name (used only by tests, via Config.TableName)
-- is NOT covered by this migration and is still created at runtime by
-- ensureCustomResultsTable in store.go, since migration files can't be
-- parameterized by a runtime-chosen identifier.

CREATE TABLE IF NOT EXISTS results (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY,
	user_id BIGINT NOT NULL,
	ts TIMESTAMPTZ NOT NULL,
	protocol TEXT NOT NULL,
	target TEXT NOT NULL,
	addr TEXT,
	port INTEGER,
	seq INTEGER,
	rtt_ms DOUBLE PRECISION,
	error TEXT,
	PRIMARY KEY (ts, id)
);

-- Safety net for a pre-existing results table from before user_id existed;
-- a no-op against the CREATE TABLE above on a fresh database.
ALTER TABLE results
	ADD COLUMN IF NOT EXISTS user_id BIGINT;

CREATE INDEX IF NOT EXISTS idx_results_user_lookup
	ON results(user_id, protocol, target, port, ts DESC);

CREATE TABLE IF NOT EXISTS users (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT NOT NULL,
	email TEXT NOT NULL,
	password_hash TEXT NOT NULL,
	verification_required BOOLEAN NOT NULL DEFAULT FALSE,
	email_verified_at TIMESTAMPTZ,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Safety net for a pre-existing users table from before these columns
-- existed; a no-op against the CREATE TABLE above on a fresh database.
ALTER TABLE users
	ADD COLUMN IF NOT EXISTS verification_required BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE users
	ADD COLUMN IF NOT EXISTS email_verified_at TIMESTAMPTZ;

CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower
	ON users (LOWER(email));

CREATE TABLE IF NOT EXISTS sessions (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	token_hash TEXT NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	expires_at TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_sessions_token_hash
	ON sessions (token_hash);

CREATE INDEX IF NOT EXISTS idx_sessions_expires_at
	ON sessions (expires_at);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	token_hash TEXT NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	expires_at TIMESTAMPTZ NOT NULL,
	used_at TIMESTAMPTZ
);

-- Safety net: keep only the newest reset token per user, in case older
-- data predates the one-active-token-per-user unique index below.
DELETE FROM password_reset_tokens a
USING password_reset_tokens b
WHERE a.user_id = b.user_id
	AND a.id < b.id;

CREATE UNIQUE INDEX IF NOT EXISTS idx_password_reset_tokens_hash
	ON password_reset_tokens (token_hash);

CREATE UNIQUE INDEX IF NOT EXISTS idx_password_reset_tokens_user_id
	ON password_reset_tokens (user_id);

CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_expires_at
	ON password_reset_tokens (expires_at);

CREATE TABLE IF NOT EXISTS email_verification_codes (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	code_hash TEXT NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	expires_at TIMESTAMPTZ NOT NULL
);

-- Safety net: keep only the newest verification code per user, in case
-- older data predates the one-active-code-per-user unique index below.
DELETE FROM email_verification_codes a
USING email_verification_codes b
WHERE a.user_id = b.user_id
	AND a.id < b.id;

-- Drop the old per-code_hash unique index this table used to have,
-- before it moved to one active code per user.
DROP INDEX IF EXISTS idx_email_verification_codes_hash;

CREATE UNIQUE INDEX IF NOT EXISTS idx_email_verification_codes_user_id
	ON email_verification_codes (user_id);

CREATE INDEX IF NOT EXISTS idx_email_verification_codes_expires_at
	ON email_verification_codes (expires_at);

CREATE INDEX IF NOT EXISTS idx_email_verification_codes_lookup
	ON email_verification_codes (user_id, code_hash, expires_at);

CREATE TABLE IF NOT EXISTS alert_rules (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	name TEXT NOT NULL,
	protocol TEXT NOT NULL,
	target TEXT NOT NULL,
	port INTEGER,
	recipient_email TEXT NOT NULL,
	latency_threshold_ms DOUBLE PRECISION,
	loss_threshold_percent DOUBLE PRECISION,
	consecutive_breaches INTEGER NOT NULL DEFAULT 1,
	cooldown_minutes INTEGER NOT NULL DEFAULT 30,
	notify_on_recovery BOOLEAN NOT NULL DEFAULT TRUE,
	enabled BOOLEAN NOT NULL DEFAULT TRUE,
	last_state TEXT NOT NULL DEFAULT 'healthy',
	current_breach_streak INTEGER NOT NULL DEFAULT 0,
	last_triggered_at TIMESTAMPTZ,
	last_recovered_at TIMESTAMPTZ,
	last_evaluated_at TIMESTAMPTZ,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_alert_rules_lookup
	ON alert_rules (user_id, protocol, target, port, enabled);
