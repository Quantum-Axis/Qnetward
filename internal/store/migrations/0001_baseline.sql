-- Baseline: the relational schema as it existed before versioned migrations.
-- Every statement is idempotent so databases created by the old setupSchema
-- adopt this version without changes. New migrations must not edit this file.

CREATE TABLE IF NOT EXISTS users (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT NOT NULL,
	email TEXT NOT NULL,
	password_hash TEXT NOT NULL,
	verification_required BOOLEAN NOT NULL DEFAULT FALSE,
	email_verified_at TIMESTAMPTZ,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE users ADD COLUMN IF NOT EXISTS verification_required BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified_at TIMESTAMPTZ;
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower ON users (LOWER(email));

CREATE TABLE IF NOT EXISTS workspaces (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	owner_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	name TEXT NOT NULL,
	plan TEXT NOT NULL DEFAULT 'starter',
	billing_status TEXT NOT NULL DEFAULT 'trial',
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE workspaces ADD COLUMN IF NOT EXISTS plan TEXT NOT NULL DEFAULT 'starter';
ALTER TABLE workspaces ADD COLUMN IF NOT EXISTS billing_status TEXT NOT NULL DEFAULT 'trial';
CREATE UNIQUE INDEX IF NOT EXISTS idx_workspaces_owner_user_id ON workspaces (owner_user_id);

CREATE TABLE IF NOT EXISTS workspace_members (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	role TEXT NOT NULL DEFAULT 'member',
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_workspace_members_workspace_user ON workspace_members (workspace_id, user_id);
CREATE INDEX IF NOT EXISTS idx_workspace_members_user_id ON workspace_members (user_id);

CREATE TABLE IF NOT EXISTS workspace_invitations (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
	inviter_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	email TEXT NOT NULL,
	role TEXT NOT NULL DEFAULT 'member',
	status TEXT NOT NULL DEFAULT 'pending',
	expires_at TIMESTAMPTZ NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_workspace_invitations_workspace_id ON workspace_invitations (workspace_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_workspace_invitations_email_status ON workspace_invitations (LOWER(email), status);

-- Every user owns a personal workspace and is its owner member.
INSERT INTO workspaces (owner_user_id, name, plan, billing_status)
SELECT u.id, CONCAT(COALESCE(NULLIF(TRIM(u.name), ''), 'Qnetward'), ' Workspace'), 'starter', 'trial'
FROM users u
WHERE NOT EXISTS (SELECT 1 FROM workspaces w WHERE w.owner_user_id = u.id);

INSERT INTO workspace_members (workspace_id, user_id, role)
SELECT w.id, w.owner_user_id, 'owner'
FROM workspaces w
WHERE NOT EXISTS (
	SELECT 1 FROM workspace_members wm WHERE wm.workspace_id = w.id AND wm.user_id = w.owner_user_id
);

CREATE TABLE IF NOT EXISTS sessions (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	token_hash TEXT NOT NULL,
	active_workspace_id BIGINT REFERENCES workspaces(id) ON DELETE SET NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	expires_at TIMESTAMPTZ NOT NULL
);
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS active_workspace_id BIGINT REFERENCES workspaces(id) ON DELETE SET NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_sessions_token_hash ON sessions (token_hash);
CREATE INDEX IF NOT EXISTS idx_sessions_expires_at ON sessions (expires_at);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	token_hash TEXT NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	expires_at TIMESTAMPTZ NOT NULL,
	used_at TIMESTAMPTZ
);
-- One outstanding reset token per user: keep the newest before adding the unique index.
DELETE FROM password_reset_tokens a USING password_reset_tokens b WHERE a.user_id = b.user_id AND a.id < b.id;
CREATE UNIQUE INDEX IF NOT EXISTS idx_password_reset_tokens_hash ON password_reset_tokens (token_hash);
CREATE UNIQUE INDEX IF NOT EXISTS idx_password_reset_tokens_user_id ON password_reset_tokens (user_id);
CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_expires_at ON password_reset_tokens (expires_at);

CREATE TABLE IF NOT EXISTS email_verification_codes (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	code_hash TEXT NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	expires_at TIMESTAMPTZ NOT NULL
);
DELETE FROM email_verification_codes a USING email_verification_codes b WHERE a.user_id = b.user_id AND a.id < b.id;
DROP INDEX IF EXISTS idx_email_verification_codes_hash;
CREATE UNIQUE INDEX IF NOT EXISTS idx_email_verification_codes_user_id ON email_verification_codes (user_id);
CREATE INDEX IF NOT EXISTS idx_email_verification_codes_expires_at ON email_verification_codes (expires_at);
CREATE INDEX IF NOT EXISTS idx_email_verification_codes_lookup ON email_verification_codes (user_id, code_hash, expires_at);

CREATE TABLE IF NOT EXISTS alert_rules (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	name TEXT NOT NULL,
	protocol TEXT NOT NULL,
	target TEXT NOT NULL,
	port INTEGER,
	recipient_email TEXT NOT NULL,
	latency_threshold_ms DOUBLE PRECISION,
	loss_threshold_percent DOUBLE PRECISION,
	consecutive_breaches INTEGER NOT NULL DEFAULT 1,
	cooldown_minutes INTEGER NOT NULL DEFAULT 30,
	notify_on_recovery BOOLEAN NOT NULL DEFAULT TRUE,
	enabled BOOLEAN NOT NULL DEFAULT TRUE,
	last_state TEXT NOT NULL DEFAULT 'healthy',
	current_breach_streak INTEGER NOT NULL DEFAULT 0,
	last_triggered_at TIMESTAMPTZ,
	last_recovered_at TIMESTAMPTZ,
	last_evaluated_at TIMESTAMPTZ,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_alert_rules_lookup ON alert_rules (user_id, protocol, target, port, enabled);
